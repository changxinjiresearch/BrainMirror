"""Exercise REAL MONAI code and NIfTI I/O with explicitly SYNTHETIC volumes.

Never describes synthetic data as a BraTS scientific validation result.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import tempfile
import numpy as np
import torch
import monai
import nibabel as nib

from brainmirror.scept.brats2020 import (
    discover_training_cases,load_case,patient_split,dice_regions,region_reference,
)
from brainmirror.scept.brats_v09_pipeline import predict_full,explain_heldout_case
from brainmirror.scept.monai_adapter import build_monai_model


def main():
    p=argparse.ArgumentParser();p.add_argument('--json-out',required=True)
    a=p.parse_args()
    torch.manual_seed(240216);torch.set_num_threads(2)
    with tempfile.TemporaryDirectory(prefix='scept_brats_v09_synthetic_') as td:
        base=Path(td);d=base/'BraTS20_Training_001';d.mkdir()
        rng=np.random.default_rng(240216)
        cube=np.zeros((32,32,32),np.float32)
        cube[3:29,3:29,3:29]=rng.normal(75,12,size=(26,26,26))
        seg=np.zeros((32,32,32),np.int16)
        seg[11:19,11:19,11:19]=2
        seg[13:17,13:17,13:17]=1
        seg[14:16,14:16,14:16]=4
        for i,suffix in enumerate(('t1','t1ce','t2','flair')):
            nib.save(nib.Nifti1Image(cube*(1+i*.04),np.eye(4)),str(d/f'{d.name}_{suffix}.nii.gz'))
        nib.save(nib.Nifti1Image(seg,np.eye(4)),str(d/f'{d.name}_seg.nii.gz'))
        x,y,qc=load_case(discover_training_cases(base)[0])
        model=build_monai_model(depths=(2,1,1,1),norm_name='batch').eval()
        probs=predict_full(model,x,patch_size=32,overlap=.25,device='cpu')
        result=explain_heldout_case(model,x,y,max_exact=3,effect_tol=1e-5)
        audit={'schema':'scept/brats2020-v09-synthetic-smoke/v1',
               'data_source':'SYNTHETIC GENERATED BY THIS SCRIPT (NO PATIENTS)',
               'clinical_validity':'NONE','scientific_validation':'NOT PERFORMED',
               'trained_model':False,'monai':monai.__version__,'torch':torch.__version__,
               'loaded_nifti':True,'input_shape':list(x.shape),
               'ground_truth_counts':qc['roi_voxels'],'predict_shape':list(probs.shape),
               'prediction_finite':bool(np.isfinite(probs).all()),
               'synthetic_dice_not_clinical_metric':dice_regions(probs,y),
               'scca_scope':result['scope'],'scca_status':result['status'],
               'scca_budget':result['path_search']['forward_budget_used'],
               'reference_qc':result['reference_qc']}
    path=Path(a.json_out);path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(audit,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(json.dumps({'validated':'synthetic_pipeline_only','nifti':True,
                      'model':'official_monai_1.5.1','scca_status':audit['scca_status']}))
    if not audit['prediction_finite'] or audit['scca_budget']>3:
        raise SystemExit('Synthetic pipeline smoke failed')

if __name__=='__main__':main()
